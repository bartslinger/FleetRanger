// Writes src/lib/ui/tokens.css from Carbon's token packages. Run `pnpm tokens`
// after upgrading @carbon/*; the output is committed so changes show in diffs.

import { writeFileSync } from 'node:fs';
import * as themes from '@carbon/themes';
import * as layout from '@carbon/layout';
import * as type from '@carbon/type';

const OUTPUT = new URL('../src/lib/ui/tokens.css', import.meta.url);

// Carbon's light and dark themes; see docs/design-system.md.
const LIGHT = { theme: themes.g10, key: 'g10' };
const DARK = { theme: themes.g100, key: 'g100' };

// Token groups for Carbon features we don't build.
const SKIPPED = /^(ai|chat|syntax)/;
const COMPONENT_TOKENS = ['buttonTokens', 'tagTokens', 'notificationTokens', 'statusTokens'];

// Lowercased like Carbon's Sass names (size2XLarge -> --cds-size-2xlarge).
const name = (token) => `--cds-${themes.formatTokenName(token).toLowerCase()}`;

function colors({ theme, key }) {
	const values = Object.entries(theme).filter(
		([token, value]) => typeof value === 'string' && !SKIPPED.test(token) && token !== 'colorScheme'
	);
	for (const group of COMPONENT_TOKENS) {
		for (const [token, byTheme] of Object.entries(themes[group])) {
			// A few component tokens exist only in light themes; leave them out.
			if (byTheme[LIGHT.key] && byTheme[DARK.key]) values.push([token, byTheme[key]]);
		}
	}
	return new Map(values);
}

const declarations = (values, indent) =>
	[...values].map(([token, value]) => `${indent}${name(token)}: ${value};`).join('\n');

function layoutTokens() {
	const tokens = [
		...Object.keys(layout).filter((token) => /^spacing\d\d$/.test(token)),
		...['sizeXSmall', 'sizeSmall', 'sizeMedium', 'sizeLarge', 'sizeXLarge', 'size2XLarge'],
		'iconSize01',
		'iconSize02'
	];
	return tokens.map((token) => `\t${name(token)}: ${layout[token]};`);
}

function typeTokens() {
	const lines = [
		`\t--cds-font-family-sans: ${type.fontFamilies.sans};`,
		`\t--cds-font-family-mono: ${type.fontFamilies.mono};`
	];
	// Fixed (productive) styles only; fluid and legacy aliases are left out.
	const styles = Object.entries(type.styles).filter(
		([style]) => !/^(fluid|expressive|productive|body(Long|Short))/.test(style)
	);
	for (const [style, values] of styles) {
		for (const [property, value] of Object.entries(values)) {
			if (property === 'breakpoints' || property === 'fontFamily') continue;
			lines.push(`\t${name(style)}-${themes.formatTokenName(property)}: ${value};`);
		}
	}
	return lines;
}

const light = colors(LIGHT);
// Only what differs from the light theme.
const dark = [...colors(DARK)].filter(([token, value]) => light.get(token) !== value);

const css = `/* Generated by scripts/tokens.js from @carbon/themes, @carbon/layout and
   @carbon/type (Apache-2.0). Don't edit; run \`pnpm tokens\`. */

:root {
\tcolor-scheme: light;
${declarations(light, '\t')}

${layoutTokens().join('\n')}

${typeTokens().join('\n')}
}

/* Dark follows the system unless the user chose light; data-theme on <html>
   holds the user's choice. */
@media (prefers-color-scheme: dark) {
\t:root:not([data-theme='light']) {
\t\tcolor-scheme: dark;
${declarations(dark, '\t\t')}
\t}
}

:root[data-theme='dark'] {
\tcolor-scheme: dark;
${declarations(dark, '\t')}
}

/* Carbon's inline theming: the dark theme for one part of the page (the
   shell), whichever theme the page has. */
.theme-dark {
\tcolor-scheme: dark;
${declarations(dark, '\t')}
\tbackground-color: var(--cds-background);
\tcolor: var(--cds-text-primary);
}
`;

writeFileSync(OUTPUT, css);
